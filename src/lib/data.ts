export const COIN_CONFIG = {
  minCustomCoins: 50,
  maxCustomCoins: 50000,
  baseRatePerCoin: 0.005, // $0.50 per 100 coins
  calculatePrice: (coins: number) => {
    const safeCoins = Math.max(50, Math.min(coins, 50000));
    let unitRate = 0.005;
    if (safeCoins >= 5000) unitRate = 0.001398;
    else if (safeCoins >= 2500) unitRate = 0.001996;
    else if (safeCoins >= 1000) unitRate = 0.00299;
    else if (safeCoins >= 500) unitRate = 0.00398;
    else if (safeCoins >= 250) unitRate = 0.00396;
    else unitRate = 0.005;

    const baseTotal = safeCoins * 0.005;
    const finalPrice = Math.max(0.50, Math.round(safeCoins * unitRate * 100) / 100);
    const originalPrice = Math.round(baseTotal * 100) / 100;
    const discountPercent = originalPrice > finalPrice ? Math.round(((originalPrice - finalPrice) / originalPrice) * 100) : 0;

    return {
      price: finalPrice,
      originalPrice,
      discountPercent,
    };
  },
};

